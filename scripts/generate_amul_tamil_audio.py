async def generate_voice(voice_name, base_name):
    mp3_path = os.path.join(OUTPUT_DIR, f"{base_name}.mp3")
    wav_path = os.path.join(OUTPUT_DIR, f"{base_name}.wav")
    m4a_path = os.path.join(OUTPUT_DIR, f"{base_name}.m4a")
    webm_path = os.path.join(OUTPUT_DIR, f"{base_name}.webm")

    print(f"🎙️ Synthesizing Tamil speech using voice: {voice_name}...")
    communicate = edge_tts.Communicate(TAMIL_SCRIPT, voice_name, rate="-2%")
    await communicate.save(mp3_path)
    print(f"✅ Generated MP3: {mp3_path} ({os.path.getsize(mp3_path) / (1024*1024):.2f} MB)")

    # Convert to WAV (16-bit PCM 24000Hz mono)
    print(f"🔄 Converting to high-fidelity WAV (PCM 16-bit)...")
    subprocess.run([
        ffmpeg_exe, "-y", "-i", mp3_path,
        "-acodec", "pcm_s16le", "-ar", "24000", "-ac", "1",
        wav_path
    ], check=True, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
    print(f"✅ Generated WAV: {wav_path} ({os.path.getsize(wav_path) / (1024*1024):.2f} MB)")

    # Convert to M4A (AAC)
    print(f"🔄 Converting to M4A (AAC 128k)...")
    subprocess.run([
        ffmpeg_exe, "-y", "-i", mp3_path,
        "-c:a", "aac", "-b:a", "128k",
        m4a_path
    ], check=True, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
    print(f"✅ Generated M4A: {m4a_path} ({os.path.getsize(m4a_path) / (1024*1024):.2f} MB)")

    # Convert to WebM (Opus)
    print(f"🔄 Converting to WebM (Opus 96k)...")
    subprocess.run([
        ffmpeg_exe, "-y", "-i", mp3_path,
        "-c:a", "libopus", "-b:a", "96k",
        webm_path
    ], check=True, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
    print(f"✅ Generated WebM: {webm_path} ({os.path.getsize(webm_path) / (1024*1024):.2f} MB)")

async def main():
    # 1. Main Male Voice (ta-IN-ValluvarNeural)
    print("\n--- Generating Amul Tamil Consultation (Male Voice) ---")
    await generate_voice("ta-IN-ValluvarNeural", "amul_consultation_tamil")

    # 2. Female Voice (ta-IN-PallaviNeural)
    print("\n--- Generating Amul Tamil Consultation (Female Voice) ---")
    await generate_voice("ta-IN-PallaviNeural", "amul_consultation_tamil_female")

    print("\n🎉 All Tamil audio files successfully created in Audio test folder!")

if __name__ == "__main__":
    asyncio.run(main())

