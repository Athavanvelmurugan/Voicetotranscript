-- 10. Add clinic_id to all Tenant Tables & Backfill
DO $$
DECLARE
  tbl text;
  tenant_tables text[] := ARRAY[
    'pets',
    'appointments',
    'consultations',
    'transcript_segments',
    'consultation_audio',
    'consultation_audio_chunks',
    'consultation_chunk_receipts',
    'clinical_extractions',
    'consultation_documents',
    'document_versions',
    'document_approvals',
    'consultation_audit_ledger',
    'consultation_audit_logs',
    'recording_consents',
    'audio_retention_policies'
  ];
BEGIN
  FOREACH tbl IN ARRAY tenant_tables
  LOOP
    IF EXISTS (SELECT 1 FROM information_schema.tables WHERE table_name = tbl AND table_schema = 'public') THEN
      -- Add column if not exists
      EXECUTE format('ALTER TABLE %I ADD COLUMN IF NOT EXISTS clinic_id INT REFERENCES clinics(id) ON DELETE CASCADE;', tbl);
      -- Backfill
      EXECUTE format('UPDATE %I SET clinic_id = 1 WHERE clinic_id IS NULL;', tbl);
      -- Enforce NOT NULL
      EXECUTE format('ALTER TABLE %I ALTER COLUMN clinic_id SET NOT NULL;', tbl);
      -- Create index
      EXECUTE format('CREATE INDEX IF NOT EXISTS %I ON %I(clinic_id);', 'idx_' || tbl || '_clinic_id', tbl);
    END IF;
  END LOOP;
END $$;

